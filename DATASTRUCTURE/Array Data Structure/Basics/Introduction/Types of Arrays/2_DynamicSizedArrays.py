# dynamic array (dynamic array create kar rahe hain)

arr = [] 

# adding elements (elements add kar rahe hain)
arr.append(10)
arr.append(20)
arr.append(30)

# printing array elements (array ke elements print kar rahe hain)
print("Array elements are:",arr)

# removing last element (aakhri element ko hata rahe hain)
arr.pop()

print("After removing last element:",arr)

# Array elements are: [10, 20, 30]
# After removing last element: [10, 20]


