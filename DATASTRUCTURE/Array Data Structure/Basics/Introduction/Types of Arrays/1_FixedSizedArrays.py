# crating a fixed-size list of 5 elements (5 elements ki ek fixed-size list create kar rahe hain)

arr = [0] * 5 
print(arr)

# Storing values in the fixed size list (list ke andar values store kar rahe hain)
for i in range(5):
    arr[i] = i + 1 
# printing list element (list ke elements ko print kar rahe hain)
print("Array elements are:", arr)

# [0, 0, 0, 0, 0] --> Fixed size array 
# Array elements are: [1, 2, 3, 4, 5]


