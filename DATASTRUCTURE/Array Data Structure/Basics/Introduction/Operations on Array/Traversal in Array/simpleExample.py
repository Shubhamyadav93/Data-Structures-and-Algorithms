arr = [10,20,30,40,50]

# 1. Using 'for' loop (value ke through traversal)
for element in arr:
    print(element,end=" ")
print() 

# 2.Using index with range() (index ke through traversal)
for i in range(len(arr)):
    print(f"Index {i} par value: {arr[i]}")



